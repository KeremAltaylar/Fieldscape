// Regenerates core/levels.hpp: run `node tools/levels.mjs` after changing a synth or the gain solve (piece.cpp comp_gains).
// Builds core/tests/composer_test.cpp (as core/tests/run.py does, em++ -O1) into build/stretch-tests/levels_table.js, runs
// its "levels-table" mode (each synth x style x rate class rendered through the engine dry against Free, ~7 min) and writes
// the table it measures: the table now plus each cell's remaining gap; a cell within 0.5 dB of nothing is 0. One run lands
// within a few tenths; run it again to settle. EM_CONFIG / the emsdk path as run.py's.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const EMSDK = 'C:/Users/kerem/tools/emsdk';
const BUILD = join(ROOT, 'build', 'stretch-tests'), OUT = join(BUILD, 'levels_table.js');
mkdirSync(BUILD, { recursive: true });
writeFileSync(join(BUILD, 'package.json'), '{"type": "commonjs"}');
const srcs = ['core.cpp', 'mix.cpp', 'place.cpp', 'webm.cpp', 'sections.cpp', 'resample.cpp', 'analysis.cpp', 'bench.cpp', 'composer.cpp', 'piece.cpp', 'engine.cpp']
  .map((f) => `core/${f}`)
  .concat(readdirSync(join(ROOT, 'core', 'devices')).filter((f) => f.endsWith('.cpp')).map((f) => `core/devices/${f}`), 'core/tests/composer_test.cpp');
execFileSync('python', [`${EMSDK}/upstream/emscripten/em++.py`, '-std=c++17', '-O1', '-DFS_TEST_O1', '-sNODERAWFS=1', '-sALLOW_MEMORY_GROWTH=1', '-sSTACK_SIZE=1048576', ...srcs, '-o', OUT],
  { cwd: ROOT, stdio: 'inherit', env: { EM_CONFIG: `${EMSDK}/.emscripten`, ...process.env } });
const text = execFileSync('node', [OUT, 'levels-table'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 24 });

const fix = Array.from({ length: 11 }, () => Array.from({ length: 6 }, () => [0, 0, 0, 0])), mel = Array(11).fill(0);
const next = (gap, now) => { const x = Math.round((+gap + +now) * 10) / 10; return Math.abs(x) < 0.5 ? 0 : x; };
for (const line of text.split('\n')) {
  const t = line.trim().split(' ');
  if (t[0] === 'LEVEL') fix[t[1]][t[2]][t[3]] = next(t[4], t[5]);
  if (t[0] === 'MELODY') mel[t[1]] = next(t[2], t[3]);
}
const NAMES = ['fm', 'am', 'duo', 'mono', 'simple', 'pluck', 'metal', 'membrane', 'wavetable', 'comb', 'formant'];
const row = (r) => `{ ${r.map((c) => `{ ${c.join(', ')} }`).join(', ')} }`;
writeFileSync(join(ROOT, 'core', 'levels.hpp'), `/* GENERATED by tools/levels.mjs - do not edit by hand. Run \`node tools/levels.mjs\` after changing a synth or the gain solve.
   Composition 2, Task 5: what the gain solve (piece.cpp comp_gains) misses of each synth's own level movement, measured
   through the whole engine dry (composer_test levels-table): a style's level over Free's, in dB, per synth (fm..formant),
   style (comp::Style; free is never corrected) and rate class (16n, 8n, 4n, 2n and slower); a melody voice's apart.
   comp_gains takes it off: g *= 10^(-fix/20) */
#pragma once
static const float LEVEL_FIX[11][6][4] = {
${fix.map((r, i) => `    ${row(r)},   /* ${NAMES[i]} */`).join('\n')}
};
static const float LEVEL_FIX_MELODY[11] = { ${mel.join(', ')} };
`);
console.log(text.trim());
